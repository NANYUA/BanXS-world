import SwiftUI

/// 翻页落位实验室的入口。
///
/// ## 为什么整个 App 只有一屏
/// 这个工程存在的唯一目的，是回答一个具体问题：**滑动翻页松手那一下，是不是先顿一下再翻**。
/// 所以要测的东西必须**一眼可达** —— 打开就是测试页，没有书架、没有书源、没有登录，
/// 也不需要在设置里翻三层才能开始。任何需要「先准备好一本书」的路径都会让测试变慢，
/// 而测试变慢就会让对比变少，对比变少就看不出差别。
///
/// ## 为什么不做多页面
/// 多一个 tab 就多一次「这个读数是在哪个上下文里测的」的疑问。这里只有一份上下文：
/// 一页正文 + 一条手势 + 一套落位动画 + 一个读数面板。
@main
struct PageTurnLabApp: App {
    var body: some Scene {
        WindowGroup {
            LabView()
        }
    }
}
